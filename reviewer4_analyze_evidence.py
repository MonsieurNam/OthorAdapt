"""Analyze the frozen Reviewer #4 dynamic-versus-static routing evidence."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import statistics
import subprocess
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
from scipy import stats


SCRIPT_VERSION = "reviewer4.analysis.v1"
PAIR_FIELDS = ("dataset", "shot", "seed")


def _key(row):
    return (str(row["dataset"]), int(row["shot"]), int(row["seed"]))


def _index(rows, label):
    index = {}
    for row in rows:
        key = _key(row)
        if key in index:
            raise ValueError(f"duplicate {label} row for {key}")
        index[key] = row
    return index


def pair_accuracy_rows(dynamic_rows, static_rows):
    dynamic = _index(dynamic_rows, "dynamic")
    static = _index(static_rows, "static")
    if set(dynamic) != set(static) or len(dynamic) != 72:
        missing_dynamic = sorted(set(static) - set(dynamic))
        missing_static = sorted(set(dynamic) - set(static))
        raise ValueError(
            f"expected the same 72 keys; missing_dynamic={missing_dynamic[:3]}, "
            f"missing_static={missing_static[:3]}"
        )
    paired = []
    for key in sorted(dynamic):
        dyn = dynamic[key]
        sta = static[key]
        if dyn.get("split_hash") != sta.get("split_hash"):
            raise ValueError(f"split hash mismatch for {key}")
        if int(dyn.get("trainable_parameters", -1)) != 460800:
            raise ValueError(f"dynamic parameter count mismatch for {key}")
        if int(sta.get("trainable_parameters", -1)) != 460800:
            raise ValueError(f"static parameter count mismatch for {key}")
        dynamic_accuracy = float(dyn["accuracy"])
        static_accuracy = float(sta["accuracy"])
        paired.append(
            {
                "dataset": key[0], "shot": key[1], "seed": key[2],
                "dynamic_accuracy": dynamic_accuracy,
                "static_accuracy": static_accuracy,
                "delta": dynamic_accuracy - static_accuracy,
                "split_hash": dyn["split_hash"],
                "trainable_parameters": 460800,
            }
        )
    return paired


def _summary(rows, tie_tolerance):
    deltas = np.asarray([float(row["delta"]) for row in rows], dtype=np.float64)
    n = int(deltas.size)
    if n == 0:
        raise ValueError("cannot summarize an empty group")
    mean = float(deltas.mean())
    sd = float(deltas.std(ddof=1)) if n > 1 else 0.0
    if n > 1:
        sem = sd / math.sqrt(n)
        critical = float(stats.t.ppf(0.975, n - 1))
        low, high = mean - critical * sem, mean + critical * sem
    else:
        low = high = mean
    wins = int(np.sum(deltas > tie_tolerance))
    ties = int(np.sum(np.abs(deltas) <= tie_tolerance))
    losses = int(np.sum(deltas < -tie_tolerance))
    dz = mean / sd if sd > 0 else (math.copysign(math.inf, mean) if mean else 0.0)
    return {
        "n": n,
        "mean_dynamic_accuracy": statistics.fmean(float(row["dynamic_accuracy"]) for row in rows),
        "mean_static_accuracy": statistics.fmean(float(row["static_accuracy"]) for row in rows),
        "mean_delta": mean,
        "ci95_low": float(low),
        "ci95_high": float(high),
        "sd_delta": sd,
        "cohens_dz": float(dz),
        "wins": wins, "ties": ties, "losses": losses,
        "wins_ties_losses": f"{wins}/{ties}/{losses}",
    }


def render_gating_ablation_table(summary, bootstrap):
    rows = [("1-shot", summary["by_shot"][0]), ("4-shot", summary["by_shot"][1]),
            ("16-shot", summary["by_shot"][2]), ("Overall", summary["overall"])]
    lines = [
        "% Auto-generated by reviewer4_analyze_evidence.py.",
        "\\begin{tabular}{lrrrr}", "\\toprule",
        "Scope & Static & Dynamic & $\\Delta$ (pp) & W/T/L \\\\", "\\midrule",
    ]
    for label, row in rows:
        lines.append(
            f"{label} & {row['mean_static_accuracy']:.3f} & {row['mean_dynamic_accuracy']:.3f} & "
            f"{row['mean_delta']:+.3f} & {row['wins_ties_losses']} \\\\"
        )
    lines.extend([
        "\\bottomrule", "\\end{tabular}",
        f"% Primary dataset-cluster bootstrap 95\\% CI: [{bootstrap['ci95_low']:+.3f}, {bootstrap['ci95_high']:+.3f}] pp.",
    ])
    return "\n".join(lines) + "\n"


def render_hierarchical_table(bootstrap, mixed_rows):
    lines = [
        "% Auto-generated primary and secondary uncertainty summaries.",
        "\\begin{tabular}{lrrr}", "\\toprule",
        "Estimand/term & Estimate & 95\\% CI low & 95\\% CI high \\\\", "\\midrule",
        f"Dataset-cluster bootstrap & {bootstrap['mean_delta']:+.3f} & {bootstrap['ci95_low']:+.3f} & {bootstrap['ci95_high']:+.3f} \\\\",
    ]
    for row in mixed_rows:
        term = str(row["term"]).replace("_", "\\_")
        lines.append(f"{term} & {row['coefficient']:+.3f} & {row['ci95_low']:+.3f} & {row['ci95_high']:+.3f} \\\\ ")
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    return "\n".join(lines) + "\n"


def render_response_evidence(summary, bootstrap):
    overall = summary["overall"]
    if bootstrap["ci95_low"] > 0:
        conclusion = "The prespecified hierarchical interval is entirely above zero, supporting a mean benefit from input-conditioned routing."
    elif bootstrap["ci95_high"] < 0:
        conclusion = "The prespecified hierarchical interval is entirely below zero; we therefore removed any claim that adaptive routing is better."
    else:
        conclusion = "The prespecified hierarchical interval includes zero, so the isolated benefit of adaptive routing is not identified and the claims are qualified accordingly."
    return (
        "### Input-conditioned versus input-independent routing evidence\n\n"
        f"Across 72 matched dataset-shot-seed pairs, input-conditioned minus input-independent routing was "
        f"{overall['mean_delta']:+.3f} percentage points (run-level paired 95% CI "
        f"[{overall['ci95_low']:+.3f}, {overall['ci95_high']:+.3f}], "
        f"$d_z={overall['cohens_dz']:.3f}$, W/T/L={overall['wins_ties_losses']}). "
        f"The prespecified dataset-cluster bootstrap 95% CI was "
        f"[{bootstrap['ci95_low']:+.3f}, {bootstrap['ci95_high']:+.3f}] percentage points. "
        f"{conclusion}\n"
    )


def write_forest_plot(summary, pdf_path, png_path):
    import matplotlib.pyplot as plt
    rows = summary["by_dataset"]
    means = np.asarray([row["mean_delta"] for row in rows])
    low = np.asarray([row["ci95_low"] for row in rows])
    high = np.asarray([row["ci95_high"] for row in rows])
    y = np.arange(len(rows))
    fig, axis = plt.subplots(figsize=(7.2, 4.8))
    axis.errorbar(means, y, xerr=np.vstack([means - low, high - means]), fmt="o", capsize=3)
    axis.axvline(0, color="black", linewidth=0.8, linestyle="--")
    axis.set_yticks(y, [row["dataset"] for row in rows])
    axis.set_xlabel("Dynamic − static accuracy (percentage points)")
    axis.set_ylabel("Dataset")
    axis.grid(axis="x", alpha=0.25)
    fig.tight_layout()
    fig.savefig(pdf_path, bbox_inches="tight")
    fig.savefig(png_path, dpi=300, bbox_inches="tight")
    plt.close(fig)


def summarize_pairs(paired, tie_tolerance=1e-12):
    by_shot = []
    for shot in (1, 4, 16):
        row = {"shot": shot, **_summary([item for item in paired if int(item["shot"]) == shot], tie_tolerance)}
        by_shot.append(row)
    by_dataset = []
    for dataset in sorted({item["dataset"] for item in paired}):
        row = {"dataset": dataset, **_summary([item for item in paired if item["dataset"] == dataset], tie_tolerance)}
        by_dataset.append(row)
    return {"overall": _summary(paired, tie_tolerance), "by_shot": by_shot, "by_dataset": by_dataset}


def dataset_cluster_bootstrap(paired, replicates=100000, seed=20261007):
    if replicates <= 0:
        raise ValueError("replicates must be positive")
    datasets = sorted({row["dataset"] for row in paired})
    if len(datasets) != 8:
        raise ValueError("hierarchical bootstrap requires exactly eight dataset clusters")
    cluster_shot_means = np.empty((len(datasets), 3), dtype=np.float64)
    for dataset_index, dataset in enumerate(datasets):
        dataset_rows = [row for row in paired if row["dataset"] == dataset]
        for shot_index, shot in enumerate((1, 4, 16)):
            values = [row["delta"] for row in dataset_rows if int(row["shot"]) == shot]
            if len(values) != 3:
                raise ValueError(f"dataset={dataset}, shot={shot} must contain three seeds")
            cluster_shot_means[dataset_index, shot_index] = float(np.mean(values))
    rng = np.random.default_rng(seed)
    sampled = rng.integers(0, len(datasets), size=(int(replicates), len(datasets)))
    bootstrap_means = cluster_shot_means[sampled].mean(axis=(1, 2))
    return {
        "estimand": "mean dynamic-minus-static accuracy; dataset-cluster bootstrap with fixed shot strata",
        "clusters": len(datasets), "replicates": int(replicates), "seed": int(seed),
        "mean_delta": float(cluster_shot_means.mean()),
        "ci95_low": float(np.percentile(bootstrap_means, 2.5)),
        "ci95_high": float(np.percentile(bootstrap_means, 97.5)),
    }


def _combined_split_hash(dataset_payload):
    split_payload = {
        "classnames_sha256": dataset_payload.get("classnames_sha256"),
        "splits": {
            name: dataset_payload.get("splits", {}).get(name, {}).get("sha256")
            for name in ("train", "val", "test")
        },
    }
    raw = json.dumps(split_payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(raw).hexdigest().upper()


def load_accuracy_manifest(path):
    rows = []
    for line_number, line in enumerate(Path(path).read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        record = json.loads(line)
        config = record.get("config", {})
        metrics = record.get("metrics", {})
        accuracy = metrics.get("test_accuracy")
        if accuracy is None:
            raise ValueError(f"missing test_accuracy at {path}:{line_number}")
        rows.append({
            "dataset": config.get("dataset"), "shot": config.get("shots"), "seed": config.get("seed"),
            "accuracy": accuracy,
            "split_hash": _combined_split_hash(record.get("dataset", {})),
            "trainable_parameters": metrics.get("trainable_parameters"),
        })
    return rows


def fit_mixed_effects(paired):
    try:
        import pandas as pd
        import statsmodels.formula.api as smf
    except ImportError as exc:
        raise RuntimeError("mixed-effects analysis requires pandas and statsmodels") from exc
    frame = pd.DataFrame(paired)
    frame["shot"] = frame["shot"].astype(str)
    frame["dataset_shot"] = frame["dataset"] + ":" + frame["shot"]
    model = smf.mixedlm(
        "delta ~ C(shot)", frame, groups=frame["dataset"],
        vc_formula={"dataset_shot": "0 + C(dataset_shot)"}, re_formula="1",
    )
    result = model.fit(reml=True, method="lbfgs")
    confidence = result.conf_int(alpha=0.05)
    rows = []
    for name in result.fe_params.index:
        rows.append({
            "term": name, "coefficient": float(result.params[name]),
            "standard_error": float(result.bse[name]),
            "ci95_low": float(confidence.loc[name, 0]),
            "ci95_high": float(confidence.loc[name, 1]),
            "converged": bool(result.converged), "optimizer": "lbfgs",
        })
    return rows


def _sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().upper()


def _git_revision():
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], check=True, capture_output=True, text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "UNKNOWN"


def _write_csv(path, rows):
    rows = list(rows)
    if not rows:
        raise ValueError(f"refusing to write empty CSV: {path}")
    with Path(path).open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def _sidecar(path, inputs):
    artifact = Path(path)
    metadata = {
        "artifact": str(artifact), "artifact_sha256": _sha256(artifact),
        "inputs": [{"path": str(Path(item)), "sha256": _sha256(item)} for item in inputs],
        "script_version": SCRIPT_VERSION, "git_revision": _git_revision(),
        "generated_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    Path(str(artifact) + ".provenance.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")


def write_outputs(
    dynamic_manifest, static_manifest, output_dir, replicates=100000,
    seed=20261007, paper_dir=None,
):
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    paper = Path(paper_dir) if paper_dir else output
    paper.mkdir(parents=True, exist_ok=True)
    inputs = [dynamic_manifest, static_manifest]
    paired = pair_accuracy_rows(load_accuracy_manifest(dynamic_manifest), load_accuracy_manifest(static_manifest))
    summary = summarize_pairs(paired)
    bootstrap = dataset_cluster_bootstrap(paired, replicates=replicates, seed=seed)
    mixed = fit_mixed_effects(paired)

    paired_path = output / "gating_paired_72.csv"
    _write_csv(paired_path, paired)
    summary_rows = [{"scope": "overall", "level": "all", **summary["overall"]}]
    summary_rows += [{"scope": "shot", "level": row.pop("shot"), **row} for row in [dict(item) for item in summary["by_shot"]]]
    summary_rows += [{"scope": "dataset", "level": row.pop("dataset"), **row} for row in [dict(item) for item in summary["by_dataset"]]]
    summary_path = output / "gating_summary_overall_shot_dataset.csv"
    _write_csv(summary_path, summary_rows)
    bootstrap_path = output / "hierarchical_bootstrap_summary.json"
    bootstrap_path.write_text(json.dumps(bootstrap, indent=2) + "\n", encoding="utf-8")
    mixed_path = output / "mixed_effects_results.csv"
    _write_csv(mixed_path, mixed)

    gating_table = paper / "gating_only_ablation_table.tex"
    gating_table.write_text(render_gating_ablation_table(summary, bootstrap), encoding="utf-8")
    hierarchical_table = paper / "hierarchical_statistics_table.tex"
    hierarchical_table.write_text(render_hierarchical_table(bootstrap, mixed), encoding="utf-8")
    response_block = paper / "response_letter_evidence_block.md"
    response_block.write_text(render_response_evidence(summary, bootstrap), encoding="utf-8")
    report = output / "reviewer4_evidence_report.md"
    report.write_text(
        "# Reviewer #4 evidence report\n\n" + render_response_evidence(summary, bootstrap),
        encoding="utf-8",
    )
    forest_pdf = paper / "dataset_level_paired_effect_forest_plot.pdf"
    forest_png = paper / "dataset_level_paired_effect_forest_plot.png"
    write_forest_plot(summary, forest_pdf, forest_png)

    for artifact in (
        paired_path, summary_path, bootstrap_path, mixed_path, gating_table,
        hierarchical_table, response_block, report, forest_pdf, forest_png,
    ):
        _sidecar(artifact, inputs)
    return {"paired": paired, "summary": summary, "bootstrap": bootstrap, "mixed_effects": mixed}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dynamic-manifest", required=True)
    parser.add_argument("--static-manifest", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--paper-dir")
    parser.add_argument("--bootstrap-replicates", type=int, default=100000)
    parser.add_argument("--bootstrap-seed", type=int, default=20261007)
    args = parser.parse_args(argv)
    write_outputs(
        args.dynamic_manifest, args.static_manifest, args.output_dir,
        replicates=args.bootstrap_replicates, seed=args.bootstrap_seed,
        paper_dir=args.paper_dir,
    )


if __name__ == "__main__":
    main()
